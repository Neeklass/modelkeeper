func ctbFile() []byte {
	b := make([]byte, 300)
	le := binary.LittleEndian
	put := func(off int, f float32) { le.PutUint32(b[off:], math.Float32bits(f)) }
	le.PutUint32(b, ctbMagicCTB)
	le.PutUint32(b[4:], 3)
	put(28, 42.5)
	put(32, 0.05)
	put(36, 2.5)
	put(40, 30)
	le.PutUint32(b[48:], 6)
	le.PutUint32(b[52:], 11520)
	le.PutUint32(b[56:], 5120)
	le.PutUint32(b[68:], 850)
	le.PutUint32(b[76:], 7260)
	le.PutUint32(b[84:], 200) // print parameters
	le.PutUint32(b[88:], 60)
	put(220, 12.75)
	put(224, 14.2)
	return b
}

func TestChitubox(t *testing.T) {
	b := ctbFile()
	info, err := Read(bytes.NewReader(b), int64(len(b)), "ctb")
	if err != nil {
		t.Fatal(err)
	}
	if info.LayerHeight != 0.05 || info.Layers != 850 || info.PrintSeconds != 7260 || info.Exposure != 2.5 ||
		info.BottomLayers != 6 || info.MaterialML != 12.75 || info.MaterialG != 14.2 || info.ResolutionX != 11520 {
		t.Errorf("%+v", info)
	}
	b[0] = 0 // not a Chitubox file
	if _, err := Read(bytes.NewReader(b), int64(len(b)), "ctb"); err != ErrUnsupported {
		t.Errorf("bad magic: %v", err)
	}
}

func TestGcode(t *testing.T) {
	prusa := "; generated by PrusaSlicer 2.7.1+win64 on 2024-01-01 at 10:00:00 UTC\n" +
		"G1 X1\n" + strings.Repeat("G1 X2 Y3\n", 60000) +
		"; filament used [mm] = 1234.5\n; filament used [g] = 3.71\n" +
		"; estimated printing time (normal mode) = 1h 2m 3s\n; layer_height = 0.2\n; filament_type = PLA\n; nozzle_diameter = 0.4\n"
	info, err := Read(strings.NewReader(prusa), int64(len(prusa)), "gcode")
	if err != nil {
		t.Fatal(err)
	}
	if info.PrintSeconds != 3723 || info.MaterialG != 3.71 || info.MaterialM != 1.23 || info.LayerHeight != 0.2 ||
		info.Material != "PLA" || info.Nozzle != 0.4 || info.Slicer != "PrusaSlicer 2.7.1+win64" {
		t.Errorf("prusa %+v", info)
	}
	cura := ";FLAVOR:Marlin\n;TIME:5400\n;Filament used: 2.5m\n;Layer height: 0.12\n;Generated with Cura_SteamEngine 5.6.0\n;LAYER_COUNT:310\nG28\n"
	info, err = Read(strings.NewReader(cura), int64(len(cura)), "gcode")
	if err != nil {
		t.Fatal(err)
	}
	if info.PrintSeconds != 5400 || info.MaterialM != 2.5 || info.LayerHeight != 0.12 || info.Layers != 310 ||
		info.Slicer != "Cura_SteamEngine 5.6.0" {
		t.Errorf("cura %+v", info)
	}
	plain := "G28\nG1 X1\n"
	if _, err := Read(strings.NewReader(plain), int64(len(plain)), "gcode"); err != ErrUnsupported {
		t.Errorf("plain: %v", err)
	}
}

func Test3MF(t *testing.T) {
	var buf bytes.Buffer
	w := zip.NewWriter(&buf)
	add := func(name, s string) {
		f, _ := w.Create(name)
		f.Write([]byte(s))
	}
	add("3D/3dmodel.model", `<?xml version="1.0"?><model><metadata name="Application">BambuStudio-01.08</metadata><resources/></model>`)
	add("Metadata/project_settings.config", `{"layer_height": "0.16", "filament_type": ["PETG"], "nozzle_diameter": ["0.4"]}`)
	add("Metadata/slice_info.config", `<config><plate><metadata key="prediction" value="3600"/><metadata key="weight" value="10.5"/></plate></config>`)
	w.Close()
	info, err := Read(bytes.NewReader(buf.Bytes()), int64(buf.Len()), "3mf")
	if err != nil {
		t.Fatal(err)
	}
	if info.LayerHeight != 0.16 || info.Material != "PETG" || info.PrintSeconds != 3600 || info.MaterialG != 10.5 ||
		info.Slicer != "BambuStudio-01.08" {
		t.Errorf("%+v", info)
	}
}
